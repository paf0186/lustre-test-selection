#!/usr/bin/env python3
"""The fixed keyword list: modules are the components of commit subjects, so a
keyword means what it does in git log, and features are chosen by hand.

  metadata/keywords.py --lustre ~/lustre-release > metadata/keywords.toml

Subjects are misspelt often enough that a typo can pass the count, so ALIASES
maps them to the real name, and the validator rejects them with that advice.
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
MIN_COMMITS = 15
ALIASES = {"pltrpc": "ptlrpc", "ldlm_": "ldlm", "oi_scrub": "scrub", "oi-scrub": "scrub",
	   "ost": "ofd", "client": "llite", "server": "mdt", "pools": "pool", "dom-mdt": "dom", "mds": "mdt"}
SKIP = {"tests", "test", "build", "doc", "docs", "misc", "kernel", "contrib", "general", "various",
	"utils", "revert", "all", "core", "libcfs", "ldiskfs", "gss", "compat"}
KEEP = {"libcfs", "ldiskfs", "gss"}
FEATURES = """dne migrate restripe striped-dir pool pfl flr mirror ec dom sel pcc hsm lfsck scrub
quota project-quota changelog nodemap encryption compression acl xattr selinux sec kerberos
recovery replay failover eviction resend lock-contention readahead pagecache direct-io mmap
truncate fallocate grant precreate orphan layout setstripe mount config-log fileset
ior-load statahead readdir rename hardlink wbc large-nid ipv6 routing discovery multi-rail
health atime fsck interop lnd""".split()


def load():
	import tomllib
	with open(HERE / "keywords.toml", "rb") as f:
		data = tomllib.load(f)
	return set(data["modules"]) | set(data["features"]), data["aliases"]


def main():
	ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
	ap.add_argument("--lustre", default=os.path.expanduser("~/lustre-release"))
	ap.add_argument("--rev", default="HEAD")
	args = ap.parse_args()
	subjects = subprocess.run(["git", "-C", args.lustre, "log", "--format=%s", "--since=2019-01-01", args.rev],
				  capture_output=True, text=True, errors="replace", check=True).stdout
	seen = Counter(re.findall(r'(?m)^LU-\d+ ([a-z][a-z0-9_-]*):', subjects))
	modules = sorted(n for n, c in seen.items()
			 if c >= MIN_COMMITS and n not in ALIASES and (n not in SKIP or n in KEEP))
	def block(xs):
		return "[\n" + "".join(f'\t"{x}",\n' for x in xs) + "]"
	print(f"# generated by metadata/keywords.py, commit components with {MIN_COMMITS}+ commits since 2019")
	print(f"modules = {block(modules)}\nfeatures = {block(sorted(set(FEATURES)))}\n\n[aliases]")
	for k, v in sorted(ALIASES.items()):
		print(f'"{k}" = "{v}"')


if __name__ == "__main__":
	main()
